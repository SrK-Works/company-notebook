// Builds dist/financial-expansion.js from content/financial-reviews/*.json. One file per company id.
const fs=require('node:fs'),path=require('node:path');
const root=path.resolve(__dirname,'..'),directory=path.join(root,'content/financial-reviews');
const entries=fs.readdirSync(directory).filter(f=>f.endsWith('.json')).sort().map(file=>{
 const id=file.slice(0,-5),record=JSON.parse(fs.readFileSync(path.join(directory,file),'utf8'));
 if(!fs.existsSync(path.join(directory,id+'.evidence.md')))throw new Error(id+': missing source evidence');
 return [id,record];
});
const output='/* Generated by scripts/build-financial-reviews.cjs. Edit content/financial-reviews/*.json. */\nwindow.COMPANY_FINANCIALS = '+JSON.stringify(Object.fromEntries(entries),null,2)+';\n';
const target=path.join(root,'dist/financial-expansion.js');
if(process.argv.includes('--check')){
 if(!fs.existsSync(target)||fs.readFileSync(target,'utf8')!==output)throw new Error('Financial bundle is stale. Run node scripts/build-financial-reviews.cjs');
 console.log(`Checked ${entries.length} independently verified financial snapshots.`);
}else{fs.writeFileSync(target,output);console.log(`Built ${entries.length} financial snapshots.`);}

// Authors edit one JSON file per company. The website serves a single generated bundle.
const fs=require('node:fs'),path=require('node:path');
const root=path.resolve(__dirname,'..'),directory=path.join(root,'content/company-lessons');
const entries=fs.readdirSync(directory).filter(f=>f.endsWith('.json')).sort().map(file=>[file.slice(0,-5),JSON.parse(fs.readFileSync(path.join(directory,file),'utf8'))]);
const output='/* Generated by scripts/build-company-lessons.cjs. Edit content/company-lessons/*.json. */\nwindow.COMPANY_LESSONS = '+JSON.stringify(Object.fromEntries(entries),null,2)+';\n';
const target=path.join(root,'dist/profile-lessons.js');
if(process.argv.includes('--check')){
 if(!fs.existsSync(target)||fs.readFileSync(target,'utf8')!==output)throw new Error('Company lessons bundle is stale. Run node scripts/build-company-lessons.cjs');
 console.log(`Checked ${entries.length} independently authored company lessons.`);
}else{fs.writeFileSync(target,output);console.log(`Built ${entries.length} company lessons.`);}

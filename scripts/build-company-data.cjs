// Authors edit one JSON file per company in content/companies/. The website serves one generated bundle.
// Each file holds the company's base record ("company") and its offering cards ("offerings").
// Lessons, financial reviews and primers are layered on top at load time, as before.
const fs=require('node:fs'),path=require('node:path');
const root=path.resolve(__dirname,'..'),directory=path.join(root,'content/companies');
const records=fs.readdirSync(directory).filter(f=>f.endsWith('.json')).map(f=>[f.slice(0,-5),JSON.parse(fs.readFileSync(path.join(directory,f),'utf8'))]);
for(const [id,r] of records){
 if(!r.company||r.company.id!==id)throw new Error(`${id}.json: company.id must equal the file name`);
 if(!Number.isInteger(r.order))throw new Error(`${id}.json: order must be a whole number`);
 if(!Array.isArray(r.offerings)||!r.offerings.length)throw new Error(`${id}.json: offerings must be a non-empty list`);
}
const orders=records.map(([,r])=>r.order);
if(new Set(orders).size!==orders.length)throw new Error('Two companies share the same order number');
records.sort((a,b)=>a[1].order-b[1].order);
const companies=records.map(([,r])=>r.company),visuals=Object.fromEntries(records.map(([id,r])=>[id,r.offerings]));
const output='/* Generated by scripts/build-company-data.cjs. Edit content/companies/*.json. */\nwindow.COMPANIES = '+JSON.stringify(companies,null,2)+';\nwindow.PRODUCT_VISUALS = '+JSON.stringify(visuals,null,2)+';\n';
const target=path.join(root,'dist/company-data.js');
if(process.argv.includes('--check')){
 if(!fs.existsSync(target)||fs.readFileSync(target,'utf8')!==output)throw new Error('Company data bundle is stale. Run node scripts/build-company-data.cjs');
 console.log(`Checked ${records.length} company records.`);
}else{fs.writeFileSync(target,output);console.log(`Built ${records.length} company records.`);}
